CREATE TABLE paper_account (
    id SMALLINT PRIMARY KEY CHECK (id = 1),
    cash_balance NUMERIC(19, 2) NOT NULL CHECK (cash_balance >= 0),
    realized_pnl NUMERIC(19, 2) NOT NULL DEFAULT 0,
    updated_at TIMESTAMPTZ NOT NULL
);

