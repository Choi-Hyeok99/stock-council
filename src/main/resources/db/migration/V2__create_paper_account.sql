CREATE TABLE paper_position (
    slot_id SMALLINT PRIMARY KEY CHECK (slot_id = 1),
    stock_code VARCHAR(12) NOT NULL UNIQUE,
    stock_name VARCHAR(100) NOT NULL,
    quantity INTEGER NOT NULL CHECK (quantity > 0),
    average_price NUMERIC(19, 2) NOT NULL CHECK (average_price > 0),
    opened_at TIMESTAMPTZ NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL
);

ALTER TABLE paper_order
    ADD COLUMN reference_price NUMERIC(19, 2),
    ADD COLUMN filled_price NUMERIC(19, 2),
    ADD COLUMN gross_amount NUMERIC(19, 2),
    ADD COLUMN message TEXT;

CREATE TABLE paper_fill (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    paper_order_id BIGINT NOT NULL REFERENCES paper_order (id),
    stock_code VARCHAR(12) NOT NULL,
    side VARCHAR(4) NOT NULL CHECK (side IN ('BUY', 'SELL')),
    quantity INTEGER NOT NULL CHECK (quantity > 0),
    fill_price NUMERIC(19, 2) NOT NULL CHECK (fill_price > 0),
    gross_amount NUMERIC(19, 2) NOT NULL CHECK (gross_amount > 0),
    occurred_at TIMESTAMPTZ NOT NULL
);

CREATE INDEX idx_paper_fill_stock_time ON paper_fill (stock_code, occurred_at);
