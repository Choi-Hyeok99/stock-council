CREATE TABLE universe_selection_run (
    id UUID PRIMARY KEY,
    rule_version VARCHAR(60) NOT NULL,
    source VARCHAR(60) NOT NULL,
    started_at TIMESTAMPTZ NOT NULL,
    completed_at TIMESTAMPTZ NOT NULL,
    ranking_received_at TIMESTAMPTZ,
    state VARCHAR(24) NOT NULL,
    selected_count SMALLINT NOT NULL CHECK (selected_count BETWEEN 0 AND 10),
    market_data JSONB NOT NULL,
    detail TEXT NOT NULL
);
CREATE TABLE universe_selection_record (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_id UUID NOT NULL REFERENCES universe_selection_run(id),
    stock_code VARCHAR(6) NOT NULL,
    stock_name VARCHAR(100) NOT NULL,
    decision VARCHAR(24) NOT NULL CHECK (decision IN ('SELECTED', 'REJECTED', 'DEFERRED')),
    reason TEXT NOT NULL,
    metrics JSONB,
    UNIQUE (run_id, stock_code)
);
CREATE INDEX idx_universe_run_time ON universe_selection_run (completed_at DESC);
