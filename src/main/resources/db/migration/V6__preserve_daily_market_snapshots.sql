-- Each selection keeps its own historical snapshot, including later corporate-action revisions.
CREATE TABLE daily_market_snapshot (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_id UUID NOT NULL REFERENCES universe_selection_run(id),
    asset_kind VARCHAR(8) NOT NULL CHECK (asset_kind IN ('STOCK', 'INDEX')),
    instrument_code VARCHAR(6) NOT NULL,
    business_date DATE NOT NULL,
    open_price NUMERIC(19, 4) NOT NULL,
    high_price NUMERIC(19, 4) NOT NULL,
    low_price NUMERIC(19, 4) NOT NULL,
    close_price NUMERIC(19, 4) NOT NULL,
    volume NUMERIC(25, 2) NOT NULL CHECK (volume >= 0),
    turnover NUMERIC(25, 2) NOT NULL CHECK (turnover >= 0),
    turnover_unit VARCHAR(40) NOT NULL,
    adjusted_price BOOLEAN NOT NULL,
    source VARCHAR(24) NOT NULL DEFAULT 'KIS_VTS_REST',
    received_at TIMESTAMPTZ NOT NULL,
    CHECK (low_price > 0 AND low_price <= high_price AND open_price BETWEEN low_price AND high_price
           AND close_price BETWEEN low_price AND high_price),
    UNIQUE (run_id, asset_kind, instrument_code, business_date)
);
CREATE INDEX idx_daily_snapshot_instrument_date ON daily_market_snapshot (asset_kind, instrument_code, business_date);
