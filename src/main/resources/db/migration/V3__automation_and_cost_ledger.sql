ALTER TABLE paper_account
    ADD COLUMN gross_realized_pnl NUMERIC(19, 2) NOT NULL DEFAULT 0,
    ADD COLUMN cumulative_costs NUMERIC(19, 2) NOT NULL DEFAULT 0,
    ADD COLUMN automation_enabled BOOLEAN NOT NULL DEFAULT TRUE;

UPDATE paper_account
SET gross_realized_pnl = realized_pnl,
    realized_pnl = 0
WHERE id = 1;

ALTER TABLE paper_position
    ADD COLUMN entry_cost NUMERIC(19, 2) NOT NULL DEFAULT 0;

ALTER TABLE paper_fill
    ADD COLUMN commission_cost NUMERIC(19, 2) NOT NULL DEFAULT 0,
    ADD COLUMN transaction_tax NUMERIC(19, 2) NOT NULL DEFAULT 0,
    ADD COLUMN slippage_cost NUMERIC(19, 2) NOT NULL DEFAULT 0,
    ADD COLUMN net_pnl NUMERIC(19, 2),
    ADD COLUMN cost_profile VARCHAR(100) NOT NULL DEFAULT 'UNVERIFIED';

CREATE TABLE automation_event (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    decision VARCHAR(40) NOT NULL,
    stock_code VARCHAR(12),
    detail TEXT NOT NULL,
    occurred_at TIMESTAMPTZ NOT NULL
);

CREATE INDEX idx_automation_event_time ON automation_event (occurred_at DESC);
