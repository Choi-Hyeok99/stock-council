CREATE TABLE analysis_record (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    stock_code VARCHAR(12) NOT NULL,
    reference_date DATE NOT NULL,
    analyzed_at TIMESTAMPTZ NOT NULL,
    market_pass BOOLEAN NOT NULL,
    stock_pass BOOLEAN NOT NULL,
    risk_pass BOOLEAN NOT NULL,
    reason TEXT NOT NULL
);

CREATE TABLE paper_order (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    request_key UUID NOT NULL UNIQUE,
    stock_code VARCHAR(12) NOT NULL,
    side VARCHAR(4) NOT NULL CHECK (side IN ('BUY', 'SELL')),
    quantity INTEGER NOT NULL CHECK (quantity > 0),
    status VARCHAR(24) NOT NULL,
    broker_order_id VARCHAR(100),
    created_at TIMESTAMPTZ NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL
);

CREATE TABLE order_event (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    paper_order_id BIGINT NOT NULL REFERENCES paper_order (id),
    event_type VARCHAR(40) NOT NULL,
    detail TEXT NOT NULL,
    occurred_at TIMESTAMPTZ NOT NULL
);

CREATE INDEX idx_paper_order_status ON paper_order (status);
CREATE INDEX idx_order_event_order ON order_event (paper_order_id, occurred_at);
