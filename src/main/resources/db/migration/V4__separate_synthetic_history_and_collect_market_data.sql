-- Keep earlier synthetic records recoverable, while excluding them from the market-data experiment.
CREATE TABLE synthetic_history_archive (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_table VARCHAR(40) NOT NULL,
    record_data JSONB NOT NULL,
    archived_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

DO $$
BEGIN
    IF EXISTS (SELECT 1 FROM paper_order WHERE stock_code NOT LIKE 'MOCK-%')
       OR EXISTS (SELECT 1 FROM paper_position WHERE stock_code NOT LIKE 'MOCK-%')
       OR EXISTS (SELECT 1 FROM analysis_record WHERE stock_code NOT LIKE 'MOCK-%') THEN
        RAISE EXCEPTION 'Archive migration requires a synthetic-only ledger; preserve non-synthetic records for review';
    END IF;
END $$;

INSERT INTO synthetic_history_archive (source_table, record_data)
SELECT 'paper_account', to_jsonb(t) FROM paper_account t UNION ALL
SELECT 'paper_position', to_jsonb(t) FROM paper_position t UNION ALL
SELECT 'paper_order', to_jsonb(t) FROM paper_order t UNION ALL
SELECT 'paper_fill', to_jsonb(t) FROM paper_fill t UNION ALL
SELECT 'order_event', to_jsonb(t) FROM order_event t UNION ALL
SELECT 'automation_event', to_jsonb(t) FROM automation_event t UNION ALL
SELECT 'analysis_record', to_jsonb(t) FROM analysis_record t;

DELETE FROM order_event;
DELETE FROM paper_fill;
DELETE FROM paper_order;
DELETE FROM paper_position;
DELETE FROM automation_event;
DELETE FROM analysis_record;
UPDATE paper_account SET cash_balance = 300000, realized_pnl = 0, gross_realized_pnl = 0,
    cumulative_costs = 0, automation_enabled = FALSE, updated_at = CURRENT_TIMESTAMP WHERE id = 1;

CREATE TABLE market_data_sample (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    stock_code VARCHAR(6) NOT NULL,
    source VARCHAR(40) NOT NULL,
    state VARCHAR(24) NOT NULL,
    price NUMERIC(19, 2) CHECK (price > 0),
    trade_at TIMESTAMPTZ,
    bar_at TIMESTAMPTZ,
    received_at TIMESTAMPTZ,
    attempted_at TIMESTAMPTZ NOT NULL,
    detail TEXT NOT NULL
);
CREATE INDEX idx_market_data_sample_time ON market_data_sample (stock_code, attempted_at DESC);
